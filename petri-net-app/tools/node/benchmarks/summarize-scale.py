#!/usr/bin/env python3
"""Summarize retained trials; plot successful solves separately from bounded exits.

Run from petri-net-app: python tools/node/benchmarks/summarize-scale.py
Requires matplotlib only for the figure. No benchmark is rerun by this script.
"""
import csv
import json
from collections import Counter
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parents[4]
OUT = ROOT / 'docs/satel/performance'
FILES = {
    'baseline': 'scaling-2026-10-17.json',
    'resource APN': 'scaling-resource-apn-2026-10-17.json',
    'diagnostic': 'scaling-diagnostic-2026-10-17.json',
    'resource diagnostic': 'scaling-resource-diagnostic-2026-10-17.json',
}
data = {name: json.loads((OUT / filename).read_text()) for name, filename in FILES.items()}


def timing(row):
    return [s.get('selectionMs', s.get('elapsedMs')) for s in row['samples']]


def label(config):
    return ', '.join(f'{k}={v}' for k, v in config.items() if k not in ('family', 'mutations', 'limits'))


rows = []
for experiment, report in data.items():
    for row in report['results']:
        samples = row['samples']
        if not samples:
            raise ValueError('No samples; inspect hard timeout before summarizing')
        times = timing(row)
        statuses = Counter(s['status'] for s in samples)
        med = lambda key: round(median(s.get(key, 0) for s in samples), 2)
        rows.append({
            'experiment': experiment, 'family': row['config']['family'], 'configuration': label(row['config']),
            'statuses': '; '.join(f'{k}:{v}' for k, v in statuses.items()),
            'selection_median_ms': median(times), 'selection_min_ms': min(times), 'selection_max_ms': max(times),
            'initialization_ms': row.get('initializationMs'), 'build_median_ms': med('buildMs'),
            'admission_median_ms': med('admissionMs'), 'replay_median_ms': med('replayMs'),
            'workflow_median_ms': round(median(sum(s.get(k, 0) for k in ('buildMs', 'selectionMs', 'admissionMs', 'replayMs')) for s in samples), 2),
            'adapter_median_ms': median(s['solver']['adapterMs'] for s in samples),
            'solver_calls_median': median(s['solver']['calls'] for s in samples),
            'max_declared_variables': max(s['solver']['maxDeclaredVariables'] for s in samples),
            'max_conditions': max(s['solver']['maxConditions'] for s in samples),
            'process_peak_rss_mib': max(s.get('peakRssMiB', 0) for s in samples),
            'limits': json.dumps(row.get('limits', {}), sort_keys=True),
            'source': FILES[experiment],
        })
with (OUT / 'scaling-summary.csv').open('w') as f:
    writer = csv.DictWriter(f, fieldnames=rows[0].keys(), lineterminator='\n')
    writer.writeheader(); writer.writerows(rows)
md = ['# Scalability measurements — all configurations', '',
      'Generated by `tools/node/benchmarks/summarize-scale.py`. Three trials per row. Times exclude Z3 initialization, model construction, concrete admission and replay. Those stages and peak process RSS are separate CSV columns. Unknown/unresolved/partial times measure stopping at a limit, not successful completion. Diagnostic rows use the separate experimental patch; some explicitly change budgets (see raw JSON and CSV).', '',
      '| Experiment | Family and configuration | Outcomes | Median ms | Min–max ms | Peak RSS MiB |',
      '|---|---|---|---:|---:|---:|']
for r in rows:
    md.append(f"| {r['experiment']} | {r['family']}: {r['configuration']} | {r['statuses']} | {r['selection_median_ms']:.2f} | {r['selection_min_ms']:.2f}–{r['selection_max_ms']:.2f} | {r['process_peak_rss_mib']:.1f} |")
(OUT / 'scaling-summary.md').write_text('\n'.join(md) + '\n')

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

plt.rcParams.update({'font.family': 'DejaVu Sans', 'font.size': 10, 'axes.spines.top': False, 'axes.spines.right': False, 'svg.fonttype': 'none', 'svg.hashsalt': 'satel-scale-2026-10-17'})
fig, axes = plt.subplots(2, 2, figsize=(12, 9), layout='constrained')
blue, orange, red = '#17678a', '#a45b1c', '#b32e37'
base = data['baseline']['results']

ax = axes[0, 0]
items = [r for r in base if r['config']['family'] == 'fulfilment' and r['config']['policies'] == 8 and r['config']['cycles'] == 4]
x = [r['samples'][0]['details']['transitions'] for r in items]
ax.plot(x, [median(timing(r))/1000 for r in items], 'o-', color=blue, label='Selection')
ax.plot(x, [median(sum(s[k] for k in ('selectionMs', 'admissionMs', 'replayMs')) for s in r['samples'])/1000 for r in items], 's-', color=orange, label='+ admission + replay')
ax.set(xscale='log', xlabel='Transition rules', ylabel='Seconds', title='A. Large fulfilment net: 20 pairs, one shared q')
ax.set_xticks(x, [str(v) for v in x]); ax.minorticks_off()
ax.legend(fontsize=9); ax.grid(alpha=.2)

ax = axes[0, 1]
for source, color, name in [('resource APN', blue, 'Baseline'), ('resource diagnostic', orange, 'Diagnostic')]:
    items = data[source]['results']
    good = [r for r in items if all(s['status'] == 'selected' for s in r['samples'])]
    bad = [r for r in items if r not in good]
    ax.plot([r['config']['size'] for r in good], [median(timing(r))/1000 for r in good], 'o-', color=color, label=name)
    ax.scatter([r['config']['size'] for r in bad], [median(timing(r))/1000 for r in bad], marker='x', color=color, s=70)
ax.set(xscale='log', xlabel='Jointly constrained method parameters', ylabel='Seconds', title='B. Resource APN: × = unresolved budget exit')
ax.set_xticks([4, 8, 16, 32, 64], ['4', '8', '16', '32', '64']); ax.minorticks_off()
ax.legend(fontsize=9); ax.grid(alpha=.2)

ax = axes[1, 0]
for nonlinear, color, name in [(False, blue, 'Fixed unit price'), (True, orange, 'Symbolic quantity × price')]:
    items = [r for r in base if r['config']['family'] == 'invoice' and r['config']['nonlinear'] == nonlinear]
    labeled = False
    for r in items:
        for s in r['samples']:
            ax.scatter(r['config']['size'], s['selectionMs']/1000, marker='o' if s['status'] == 'sat' else 'x', color=color, label=name if not labeled else None, s=40, alpha=.75)
            labeled = True
ax.set(xscale='log', yscale='log', xlabel='Custom ADT invoice lines', ylabel='Seconds per trial', title='C. ADT unfolding + SMT: × = unknown')
ax.set_xticks([2, 4, 8, 16, 32], ['2', '4', '8', '16', '32']); ax.xaxis.set_minor_locator(matplotlib.ticker.NullLocator())
ax.legend(fontsize=9); ax.grid(alpha=.2)

ax = axes[1, 1]
queries = [(4, 2, False), (2, 4, False), (2, 4, True)]
for i, (workers, rounds, audit) in enumerate(queries):
    for offset, source, color, name in [(-.18, 'baseline', blue, 'Baseline'), (.18, 'diagnostic', orange, 'Diagnostic')]:
        r = next(r for r in data[source]['results'] if r['config']['family'] == 'workers' and (r['config']['workers'], r['config']['rounds'], r['config']['audit']) == (workers, rounds, audit))
        ok = all(s['status'] == 'selected' for s in r['samples'])
        value = median(timing(r))/1000
        ax.bar(i + offset, value, .34, color=color, hatch=None if ok else '///', label=name if i == 0 else None)
        ax.text(i + offset, value*1.07, f'{value:.2f}' + ('' if ok else '*'), ha='center', fontsize=9)
ax.set(yscale='log', ylim=(.06, 20), ylabel='Seconds (log scale)', title='D. Joint HML selection: * = budget exhausted')
ax.set_xticks(range(3), ['4 workers\n2 rounds', '2 workers\n4 rounds', '2 workers\n4 rounds + audit'])
ax.legend(fontsize=9); ax.grid(axis='y', alpha=.2)
fig.suptitle('SATEL scalability — bounded workloads, 17 October 2026', fontsize=16)
fig.savefig(OUT / 'scaling-2026-10-17.png', dpi=180)
fig.savefig(OUT / 'scaling-2026-10-17.svg', metadata={'Date': None})
svg = OUT / 'scaling-2026-10-17.svg'
svg.write_text('\n'.join(line.rstrip() for line in svg.read_text().splitlines()) + '\n')
print(f'Wrote {len(rows)} configuration summaries and the figure to {OUT}')
